    def __getitem__(self, key):
        """Allow access like levels[("EC", 1)]"""
        return self._mapping[key]

    def get(self, area_name, level_number):
        """Get the combined name"""
        return self._mapping.get((area_name, level_number))

    def lookup(self, combined_name):
        """Find the area and level for a given combined name"""
        for (area, level), name in self._mapping.items():
            if name == combined_name:
                return area, level
        return None, None


